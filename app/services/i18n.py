def normalize_language(language: str | None) -> str:
    normalized = (language or DEFAULT_INTERFACE_LANGUAGE).strip().upper()
    if normalized not in SUPPORTED_INTERFACE_LANGUAGES:
        return DEFAULT_INTERFACE_LANGUAGE
    return normalized


def html_language(language: str | None) -> str:
    return "en" if normalize_language(language) == "EN" else "ru"


def translate(language: str | None, key: str, **kwargs) -> str:
    normalized = normalize_language(language)
    text = TRANSLATIONS.get(normalized, TRANSLATIONS[DEFAULT_INTERFACE_LANGUAGE]).get(
        key,
        TRANSLATIONS[DEFAULT_INTERFACE_LANGUAGE].get(key, key),
    )
    if kwargs:
        return text.format(**kwargs)
    return text


def translate_error_message(language: str | None, message: str) -> str:
    normalized = normalize_language(language)
    if normalized == DEFAULT_INTERFACE_LANGUAGE:
        return message

    exact = ERROR_TRANSLATIONS.get(message)
    if exact and normalized in exact:
        return exact[normalized]

    for pattern, translations in ERROR_PATTERNS:
        match = pattern.match(message)
        if match and normalized in translations:
            return translations[normalized].format(**match.groupdict())

    return message


def make_translator(language: str | None):
    normalized = normalize_language(language)

    def _translate(key: str, **kwargs) -> str:
        return translate(normalized, key, **kwargs)

    return _translate
